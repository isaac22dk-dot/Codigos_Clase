class Valores_Reales:
    """Implementacion del TAD Valores Reales"""

    def division(self, numero1: float, numero2: float) -> float:
        return numero1 / numero2
    def raiz_cuadrada(self, numero: float) -> float:
        return numero ** 0.5
    def complexion(self, numero1: float, numero2: float) -> complex:
        return complex(numero1, numero2)
